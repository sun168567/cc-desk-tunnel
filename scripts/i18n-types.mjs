import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';

// The types of the catalogs, from the source language's: every key, and each message as the literal it is, from
// which i18next tells the values a message is filled in with (`{{name}}`). JSON imports give TypeScript only
// `string`, so they are written out here; packages/i18n/test/catalogs.test.mjs fails while this file is out of
// date. Run `node scripts/i18n-types.mjs` after changing a zh-CN catalog.
//
// `Messages` gives each message, `namespace:key`, the values a phrase of it carries (see src/phrase.ts): a
// plural's `count`, a list for a value formatted as one, any other value as it is or words of its own.
const root = fileURLToPath(new URL('..', import.meta.url));
const source = join(root, 'packages/i18n/src/locales/zh-CN');
export const typesFile = join(root, 'packages/i18n/src/resources.d.ts');

const literal = (value) => JSON.stringify(value);
function typeOf(value, indent) {
  if (typeof value === 'string') return literal(value);
  const inner = `${indent}  `;
  const fields = Object.entries(value).map(
    ([key, child]) => `${inner}${literal(key)}: ${typeOf(child, inner)};`,
  );
  return `{\n${fields.join('\n')}\n${indent}}`;
}

const lists = new Set(['quoted', 'clauses', 'parts', 'series', 'commas']);
function messageTypes(namespace, catalog) {
  const flat = (tree, prefix = '') =>
    Object.entries(tree).flatMap(([key, value]) =>
      typeof value === 'string' ? [[prefix + key, value]] : flat(value, `${prefix}${key}.`),
    );
  const messages = new Map();
  for (const [key, text] of flat(catalog)) {
    const plural = /_other$/.test(key);
    const name = `${namespace}:${key.replace(/_other$/, '')}`;
    const values = messages.get(name) ?? new Map();
    if (plural) values.set('count', 'number');
    for (const [, value, format] of text.matchAll(/\{\{\s*([^,}\s]+)\s*(?:,\s*([^}\s]+)\s*)?\}\}/g))
      if (value !== 'count' || !plural)
        values.set(value, lists.has(format) ? 'ListValue' : 'Value');
    messages.set(name, values);
  }
  return [...messages].map(([name, values]) => {
    const fields = [...values].map(([value, type]) => `${literal(value)}: ${type}`);
    return `  ${literal(name)}: ${fields.length ? `{ ${fields.join('; ')} }` : 'Record<string, never>'};`;
  });
}

export async function resourceTypes() {
  const namespaces = readdirSync(source)
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort();
  const catalogs = namespaces.map((name) => [
    name,
    JSON.parse(readFileSync(join(source, `${name}.json`), 'utf8')),
  ]);
  const body = catalogs
    .map(([name, catalog]) => `  ${literal(name)}: ${typeOf(catalog, '  ')};`)
    .join('\n');
  const messages = catalogs.flatMap(([name, catalog]) => messageTypes(name, catalog)).join('\n');
  const text = `// Generated by scripts/i18n-types.mjs from the zh-CN catalogs; do not edit.\nimport type { ListValue, Value } from './phrase.ts';\n\nexport type Resources = {\n${body}\n};\nexport type Messages = {\n${messages}\n};\n`;
  return format(text, { ...(await resolveConfig(typesFile)), filepath: typesFile });
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(typesFile, await resourceTypes());
  console.log(`Wrote ${typesFile}.`);
}
