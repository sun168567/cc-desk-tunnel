import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';

// The types of the catalogs, from the source language's: every key, and each message as the literal it is, from
// which i18next tells the values a message is filled in with (`{{name}}`). JSON imports give TypeScript only
// `string`, so they are written out here; packages/i18n/test/catalogs.test.ts fails while this file is out of
// date. Run `node scripts/i18n-types.mjs` after changing a zh-CN catalog.
const root = fileURLToPath(new URL('..', import.meta.url));
const source = join(root, 'packages/i18n/src/locales/zh-CN');
export const typesFile = join(root, 'packages/i18n/src/resources.d.ts');

const literal = (value) => JSON.stringify(value);
function typeOf(value, indent) {
  if (typeof value === 'string') return literal(value);
  const inner = `${indent}  `;
  const fields = Object.entries(value).map(
    ([key, child]) => `${inner}${literal(key)}: ${typeOf(child, inner)};`,
  );
  return `{\n${fields.join('\n')}\n${indent}}`;
}

export async function resourceTypes() {
  const namespaces = readdirSync(source)
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort();
  const body = namespaces
    .map((name) => {
      const catalog = JSON.parse(readFileSync(join(source, `${name}.json`), 'utf8'));
      return `  ${literal(name)}: ${typeOf(catalog, '  ')};`;
    })
    .join('\n');
  const text = `// Generated by scripts/i18n-types.mjs from the zh-CN catalogs; do not edit.\nexport type Resources = {\n${body}\n};\n`;
  return format(text, { ...(await resolveConfig(typesFile)), filepath: typesFile });
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(typesFile, await resourceTypes());
  console.log(`Wrote ${typesFile}.`);
}
